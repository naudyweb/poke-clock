#!/usr/bin/env python3
"""Generate firmware/src/poke_sprites.h from pixel_art.py and screens.py."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

import pixel_art  # noqa: E402
import screens  # noqa: E402

OUT_PATH = ROOT_DIR / "firmware" / "src" / "poke_sprites.h"
GBC_ALERT_RED_HEX = "#E83838"

WEATHER_ICON_SPECS: tuple[tuple[str, list[str], dict[str, str]], ...] = (
    ("sun", pixel_art.MINI_SUN, pixel_art.MINI_SUN_PAL),
    ("cloud", pixel_art.MINI_CLOUD, pixel_art.MINI_CLOUD_PAL),
    ("rain", pixel_art.MINI_RAIN, pixel_art.MINI_RAIN_PAL),
    ("storm", pixel_art.MINI_STORM, pixel_art.MINI_STORM_PALETTE),
    ("moon", pixel_art.MINI_MOON, pixel_art.MINI_MOON_PAL),
)


def hex_to_rgb565(hex_color: str) -> int:
    h = hex_color.strip().lstrip("#")
    if len(h) != 6:
        raise ValueError(f"Expected #RRGGBB hex color, got {hex_color!r}")
    r = int(h[0:2], 16)
    g = int(h[2:4], 16)
    b = int(h[4:6], 16)
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def pack_sprite_4bit(
    grid: list[str],
    palette: dict[str, str],
    expected_w: int,
    expected_h: int,
    name: str,
) -> tuple[list[int], list[int]]:
    """Encode an ASCII sprite grid into 4-bit packed rows and a 16-entry RGB565 palette."""
    if len(grid) != expected_h:
        raise ValueError(f"{name}: expected {expected_h} rows, got {len(grid)}")

    char_to_idx: dict[str, int] = {".": 0}
    pal_565: list[int] = [0x0000] * 16
    next_idx = 1

    for row in grid:
        if len(row) != expected_w:
            raise ValueError(f"{name}: expected row width {expected_w}, got {len(row)} in {row!r}")
        for ch in row:
            if ch == ".":
                continue
            if ch not in palette:
                raise ValueError(f"{name}: color key {ch!r} missing from palette")
            if ch not in char_to_idx:
                if next_idx >= 16:
                    raise ValueError(f"{name}: exceeds 15 non-transparent colors for 4-bit packing")
                char_to_idx[ch] = next_idx
                pal_565[next_idx] = hex_to_rgb565(palette[ch])
                next_idx += 1

    packed: list[int] = []
    for row in grid:
        for x in range(0, expected_w, 2):
            p0 = char_to_idx[row[x]]
            p1 = char_to_idx[row[x + 1]] if (x + 1) < expected_w else 0
            packed.append(((p0 & 0x0F) << 4) | (p1 & 0x0F))

    return packed, pal_565


def _format_hex_bytes(data: list[int], per_line: int) -> str:
    lines: list[str] = []
    for i in range(0, len(data), per_line):
        chunk = ", ".join(f"0x{b:02X}" for b in data[i : i + per_line])
        lines.append(f"    {chunk},")
    return "\n".join(lines)


def _format_hex_words(data: list[int], per_line: int = 8) -> str:
    lines: list[str] = []
    for i in range(0, len(data), per_line):
        chunk = ", ".join(f"0x{w:04X}" for w in data[i : i + per_line])
        lines.append(f"    {chunk},")
    return "\n".join(lines)


def build_header() -> tuple[str, dict[str, int]]:
    parts: list[str] = [
        "// Auto-generated by scripts/gen_firmware_sprites.py from pixel_art.py and screens.py.",
        "// Do not edit manually.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "#include <TFT_eSPI.h>",
        "",
        f"static constexpr uint8_t POKE_SPRITE_COUNT = {len(screens.OFFLINE_POKEMON_ORDER)};",
        "static constexpr uint8_t POKE_SPRITE_W = 18;",
        "static constexpr uint8_t POKE_SPRITE_H = 18;",
        "static constexpr uint8_t POKE_SPRITE_ROW_BYTES = 9;",
        "static constexpr uint8_t POKE_SPRITE_BYTES = 162;",
        "",
        f"static constexpr uint8_t GBC_PALETTE_COUNT = {len(screens.OFFLINE_PALETTE_ORDER)};",
        "",
        f"static constexpr uint8_t WEATHER_ICON_COUNT = {len(WEATHER_ICON_SPECS)};",
        "static constexpr uint8_t WEATHER_ICON_W = 7;",
        "static constexpr uint8_t WEATHER_ICON_H = 7;",
        "static constexpr uint8_t WEATHER_ICON_ROW_BYTES = 4;",
        "static constexpr uint8_t WEATHER_ICON_BYTES = 28;",
        "",
        "enum WeatherIconIndex : uint8_t {",
        "  WEATHER_ICON_SUN = 0,",
        "  WEATHER_ICON_CLOUD = 1,",
        "  WEATHER_ICON_RAIN = 2,",
        "  WEATHER_ICON_STORM = 3,",
        "  WEATHER_ICON_MOON = 4,",
        "};",
        "",
    ]

    poke_pixel_bytes = 0
    poke_pal_bytes = 0
    poke_entries: list[str] = []

    for name in screens.OFFLINE_POKEMON_ORDER:
        grid, pal, accent_hex = screens.SPRITE_CATALOG[name]
        packed, pal_565 = pack_sprite_4bit(grid, pal, 18, 18, name)
        accent_565 = hex_to_rgb565(accent_hex)
        upper = name.upper()
        poke_pixel_bytes += len(packed)
        poke_pal_bytes += len(pal_565) * 2

        parts.append(f"static const uint16_t POKE_PAL_{upper}[16] PROGMEM = {{")
        parts.append(_format_hex_words(pal_565, per_line=8))
        parts.append("};")
        parts.append(f"static const uint8_t POKE_PIXELS_{upper}[POKE_SPRITE_BYTES] PROGMEM = {{")
        parts.append(_format_hex_bytes(packed, per_line=9))
        parts.append("};")
        parts.append("")
        poke_entries.append(
            f'    {{"{name}", 0x{accent_565:04X}, POKE_PAL_{upper}, POKE_PIXELS_{upper}}},'
        )

    parts.extend([
        "struct PokeSprite565 {",
        "  const char* name;",
        "  uint16_t accent;",
        "  const uint16_t* palette;",
        "  const uint8_t* pixels;",
        "};",
        "",
        "static const PokeSprite565 POKE_SPRITES[POKE_SPRITE_COUNT] = {",
        *poke_entries,
        "};",
        "",
    ])

    # 4 GBC Palettes
    parts.extend([
        "struct GbcPalette565 {",
        "  uint16_t bg;",
        "  uint16_t card;",
        "  uint16_t border;",
        "  uint16_t ink;",
        "  uint16_t muted;",
        "  uint16_t top_band;",
        "  uint16_t blue;",
        "  uint16_t green;",
        "  uint16_t dither;",
        "  uint16_t pad_top;",
        "  uint16_t pad_mid;",
        "  uint16_t pad_bot;",
        "  uint16_t divider;",
        "  uint16_t red;",
        "};",
        "",
        "static const char* const GBC_PALETTE_NAMES[GBC_PALETTE_COUNT] = {",
    ])
    for pname in screens.OFFLINE_PALETTE_ORDER:
        parts.append(f'    "{pname}",')
    parts.extend([
        "};",
        "",
        "static const GbcPalette565 GBC_PALETTES[GBC_PALETTE_COUNT] = {",
    ])

    alert_red_565 = hex_to_rgb565(GBC_ALERT_RED_HEX)
    pal_fields = (
        "bg",
        "card",
        "border",
        "ink",
        "muted",
        "top_band",
        "blue",
        "green",
        "dither",
        "pad_top",
        "pad_mid",
        "pad_bot",
        "divider",
    )
    for pname in screens.OFFLINE_PALETTE_ORDER:
        p = screens.PALETTES[pname]
        vals = [f"0x{hex_to_rgb565(p[field]):04X}" for field in pal_fields]
        vals.append(f"0x{alert_red_565:04X}")
        parts.append(f"    // {pname}")
        parts.append(f"    {{{', '.join(vals)}}},")
    parts.extend([
        "};",
        "",
    ])

    # 5 Weather Icons (7x7)
    weather_pixel_bytes = 0
    weather_pal_bytes = 0
    weather_entries: list[str] = []

    for wname, wgrid, wpal in WEATHER_ICON_SPECS:
        packed, pal_565 = pack_sprite_4bit(wgrid, wpal, 7, 7, f"weather:{wname}")
        upper = wname.upper()
        weather_pixel_bytes += len(packed)
        weather_pal_bytes += len(pal_565) * 2

        parts.append(f"static const uint16_t WEATHER_PAL_{upper}[16] PROGMEM = {{")
        parts.append(_format_hex_words(pal_565, per_line=8))
        parts.append("};")
        parts.append(f"static const uint8_t WEATHER_PIXELS_{upper}[WEATHER_ICON_BYTES] PROGMEM = {{")
        parts.append(_format_hex_bytes(packed, per_line=4))
        parts.append("};")
        parts.append("")
        weather_entries.append(
            f'    {{"{wname}", WEATHER_PAL_{upper}, WEATHER_PIXELS_{upper}}},'
        )

    parts.extend([
        "struct WeatherIcon565 {",
        "  const char* name;",
        "  const uint16_t* palette;",
        "  const uint8_t* pixels;",
        "};",
        "",
        "static const WeatherIcon565 WEATHER_ICONS[WEATHER_ICON_COUNT] = {",
        *weather_entries,
        "};",
        "",
    ])

    # Helpers
    parts.extend([
        "static inline bool _eqIgnoreCase(const char* a, const char* b) {",
        "  if (a == nullptr || b == nullptr) return false;",
        "  while (*a && *b) {",
        "    char ca = (*a >= 'A' && *a <= 'Z') ? (*a + ('a' - 'A')) : *a;",
        "    char cb = (*b >= 'A' && *b <= 'Z') ? (*b + ('a' - 'A')) : *b;",
        "    if (ca != cb) return false;",
        "    ++a;",
        "    ++b;",
        "  }",
        "  return *a == *b;",
        "}",
        "",
        "static inline uint8_t pokeNameToIndex(const char* name) {",
        "  if (name == nullptr || name[0] == '\\0') return 0;",
        "  for (uint8_t i = 0; i < POKE_SPRITE_COUNT; ++i) {",
        "    if (_eqIgnoreCase(name, POKE_SPRITES[i].name)) return i;",
        "  }",
        "  return 0;",
        "}",
        "",
        "static inline uint8_t paletteNameToIndex(const char* name) {",
        "  if (name == nullptr || name[0] == '\\0') return 0;",
        "  for (uint8_t i = 0; i < GBC_PALETTE_COUNT; ++i) {",
        "    if (_eqIgnoreCase(name, GBC_PALETTE_NAMES[i])) return i;",
        "  }",
        "  return 0;",
        "}",
        "",
        "static inline void _drawPacked4Sprite565(",
        "    TFT_eSPI& tft,",
        "    const uint8_t* pixels,",
        "    const uint16_t* palette,",
        "    uint8_t w,",
        "    uint8_t h,",
        "    uint8_t rowBytes,",
        "    int16_t x0,",
        "    int16_t y0,",
        "    uint8_t scale) {",
        "  if (scale == 0 || pixels == nullptr || palette == nullptr || w > POKE_SPRITE_W) return;",
        "  uint8_t line[POKE_SPRITE_W];",
        "  for (uint8_t row = 0; row < h; ++row) {",
        "    const uint16_t rowBase = static_cast<uint16_t>(row) * rowBytes;",
        "    for (uint8_t b = 0; b < rowBytes; ++b) {",
        "      const uint8_t packed = pgm_read_byte(&pixels[rowBase + b]);",
        "      const uint8_t x = static_cast<uint8_t>(b * 2);",
        "      if (x < w) line[x] = (packed >> 4) & 0x0F;",
        "      if (x + 1 < w) line[x + 1] = packed & 0x0F;",
        "    }",
        "    uint8_t col = 0;",
        "    while (col < w) {",
        "      const uint8_t cIdx = line[col];",
        "      if (cIdx == 0) {",
        "        ++col;",
        "        continue;",
        "      }",
        "      uint8_t run = 1;",
        "      while (col + run < w && line[col + run] == cIdx) {",
        "        ++run;",
        "      }",
        "      const uint16_t color = pgm_read_word(&palette[cIdx]);",
        "      tft.fillRect(",
        "          x0 + static_cast<int16_t>(col) * scale,",
        "          y0 + static_cast<int16_t>(row) * scale,",
        "          static_cast<int16_t>(run) * scale,",
        "          scale,",
        "          color);",
        "      col += run;",
        "    }",
        "  }",
        "}",
        "",
        "static inline void drawPokeSprite565(",
        "    TFT_eSPI& tft,",
        "    uint8_t idx,",
        "    int16_t x0,",
        "    int16_t y0,",
        "    uint8_t scale) {",
        "  if (idx >= POKE_SPRITE_COUNT) idx = 0;",
        "  _drawPacked4Sprite565(",
        "      tft,",
        "      POKE_SPRITES[idx].pixels,",
        "      POKE_SPRITES[idx].palette,",
        "      POKE_SPRITE_W,",
        "      POKE_SPRITE_H,",
        "      POKE_SPRITE_ROW_BYTES,",
        "      x0,",
        "      y0,",
        "      scale);",
        "}",
        "",
        "static inline void drawWeatherIcon565(",
        "    TFT_eSPI& tft,",
        "    uint8_t iconIdx,",
        "    int16_t x0,",
        "    int16_t y0,",
        "    uint8_t scale) {",
        "  if (iconIdx >= WEATHER_ICON_COUNT) iconIdx = 0;",
        "  _drawPacked4Sprite565(",
        "      tft,",
        "      WEATHER_ICONS[iconIdx].pixels,",
        "      WEATHER_ICONS[iconIdx].palette,",
        "      WEATHER_ICON_W,",
        "      WEATHER_ICON_H,",
        "      WEATHER_ICON_ROW_BYTES,",
        "      x0,",
        "      y0,",
        "      scale);",
        "}",
        "",
    ])

    stats = {
        "poke_pixel_bytes": poke_pixel_bytes,
        "poke_pal_bytes": poke_pal_bytes,
        "weather_pixel_bytes": weather_pixel_bytes,
        "weather_pal_bytes": weather_pal_bytes,
        "total_progmem_bytes": poke_pixel_bytes + poke_pal_bytes + weather_pixel_bytes + weather_pal_bytes,
    }
    return "\n".join(parts), stats


def main() -> None:
    content, stats = build_header()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(content, encoding="utf-8")
    print(
        f"Generated {OUT_PATH} | "
        f"sprites={stats['poke_pixel_bytes']}B + pal={stats['poke_pal_bytes']}B, "
        f"weather={stats['weather_pixel_bytes']}B + pal={stats['weather_pal_bytes']}B, "
        f"total PROGMEM={stats['total_progmem_bytes']}B"
    )


if __name__ == "__main__":
    main()
